const endgameMaterial = 1300

func Evaluate(p *chess.Position) int {
	endgame := officerMaterial(p) <= endgameMaterial
	score := 0
	for sq, pc := range p.Board {
		if pc.Empty() {
			continue
		}
		v := pieceValue[pc.Kind] + bonus(pc, sq, endgame)
		if pc.Color == chess.White {
			score += v
		} else {
			score -= v
		}
	}
	if p.Turn == chess.Black {
		return -score
	}
	return score
}

func officerMaterial(p *chess.Position) int {
	total := 0
	for _, pc := range p.Board {
		if pc.Kind != chess.Pawn {
			total += pieceValue[pc.Kind]
		}
	}
	return total
}

func bonus(pc chess.Piece, sq int, endgame bool) int {
	row := chess.RankOf(sq)
	if pc.Color == chess.White {
		row = 7 - row
	}
	idx := row*8 + chess.FileOf(sq)
	if pc.Kind == chess.King && endgame {
		return kingEndgameBonus[idx]
	}
	return squareBonus[pc.Kind][idx]
}
